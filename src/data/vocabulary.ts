export const wordById = (id: string): VocabWord | undefined => VOCABULARY.find((w) => w.id === id);

export const wordsByLevel = (level: Level): VocabWord[] => VOCABULARY.filter((w) => w.level === level);

/** Finds a vocabulary word mentioned inside free text (whole-word match). */
export function findWordInText(text: string): VocabWord | undefined {
  const t = text.toLowerCase();
  return VOCABULARY.find((w) => new RegExp(`\\b${w.word}\\b`).test(t));
}
